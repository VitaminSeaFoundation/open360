import Foundation
import simd

/// Writes the analysis sidecar consumed by the "open360 Reframe" Fusion Fuse.
/// The file is a Lua chunk (`return { ... }`) so the Fuse can load it with no JSON parser.
/// Lens parameters are normalised to the lens image size (u,v in 0..1, v measured from the top).
enum Sidecar {
    static func f(_ v: Double, _ digits: Int = 7) -> String {
        if !v.isFinite { return "0" }
        return String(format: "%.\(digits)g", v)
    }

    static func write(to url: URL, meta: InsvMetadata, stitcher: Stitcher, fps: Double, frames: Int,
                      modes: [String: [simd_double3x3]], source: String, separate: Bool) throws {
        var s = "-- open360 Reframe sidecar (generated by open360-stitch --analyze). Do not edit.\n"
        s += "return {\n"
        s += "  version = 1,\n"
        s += "  source = \(luaString(source)),\n"
        s += "  camera = \(luaString(meta.cameraModel)), firmware = \(luaString(meta.firmware)), log = \(luaString(meta.logMode)),\n"
        s += "  fps = \(f(fps)), frames = \(frames),\n"
        switch stitcher.layout {
        case .separateTracks: s += "  layout = \"tracks\",\n"
        case .sideBySide(let sw): s += "  layout = \"\(sw ? "sbs_swapped" : "sbs")\",\n"
        }
        let st = stitcher.settings
        s += "  stitch = { distance = \(st.distance.map { f($0) } ?? "0"), gain = \(f(st.lens1Gain)), feather = \(f(st.featherDeg)), "
        s += "accessory = \(luaString(st.accessory.rawValue)), radiusScale = \(f(st.radiusScale.0)) },\n"
        s += "  readout = \(f(meta.readoutTime)),\n"
        s += "  lenses = {\n"
        for (li, c) in meta.lenses.prefix(2).enumerated() {
            let ls = c.lensSize, fw = c.focalWindow
            let R = Stitcher.lensRotation(c)
            let rows = (0..<3).flatMap { r in [R[0][r], R[1][r], R[2][r]] }.map { f($0) }.joined(separator: ", ")
            let sg = st.translationSign
            s += "    { xi = \(f(c.xi)), fx = \(f(c.fx / fw)), fy = \(f(c.fy / fw)), "
            s += "cx = \(f(c.cx.truncatingRemainder(dividingBy: ls) / ls)), cy = \(f(c.cy / ls)),\n"
            s += "      k = { \(f(c.k.0)), \(f(c.k.1)), \(f(c.k.2)), \(f(c.k.3)) },\n"
            s += "      p = { \(f(c.p.0)), \(f(c.p.1)) }, s = { \(f(c.s.0)), \(f(c.s.1)), \(f(c.s.2)), \(f(c.s.3)) },\n"
            let rr = st.radial(li)
            s += "      scale = \(f(rr.0)), radial = { \(f(rr.0)), \(f(rr.1)), \(f(rr.2)) },\n"
            s += "      t = { \(f(c.translation.0 * sg)), \(f(c.translation.1 * sg)), \(f(c.translation.2 * sg)) },\n"
            s += "      R = { \(rows) }, radius = 0.4925 },\n"
        }
        s += "  },\n"
        // per-frame view->body rotation as quaternions "w x y z" (space separated string;
        // long clips would exceed Lua's constant limits as table literals)
        s += "  stab = {\n"
        for (name, mats) in modes.sorted(by: { $0.key < $1.key }) {
            s += "    \(name) = \""
            var parts: [String] = []
            parts.reserveCapacity(mats.count * 4)
            for m in mats {
                let q = simd_quatd(m)
                parts += [f(q.real, 6), f(q.imag.x, 6), f(q.imag.y, 6), f(q.imag.z, 6)]
            }
            s += parts.joined(separator: " ")
            s += "\",\n"
        }
        s += "  },\n}\n"
        let tmp = url.appendingPathExtension("tmp")
        try s.write(to: tmp, atomically: true, encoding: .utf8)
        _ = try? FileManager.default.removeItem(at: url)
        try FileManager.default.moveItem(at: tmp, to: url)
    }

    static func luaString(_ s: String) -> String {
        "\"" + s.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"").replacingOccurrences(of: "\n", with: "\\n") + "\""
    }
}
